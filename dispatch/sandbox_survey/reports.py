        "the attestation is true. Open the file to see who and what.",
        "",
        *_table(
            ("path", "attestation claims in sample", "modified (UTC)", "secondary"),
            [(record["relpath"], record["attestation_claims"], record["modified"] or "-",
              _classes(record))
             for record in sorted(recorded, key=lambda item: item["relpath"])],
        ),
        "",
        "## Decision candidates (downgraded — no identifiable actor, or AI-generated)",
        "",
        f"{len(candidates)} files. Each carries decision language without an identifiable "
        "human actor, or reads as AI-generated. Each is a question for Mike: was this "

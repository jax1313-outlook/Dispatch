def sensitive_material_report(data: dict[str, Any]) -> str:
    lines = header_lines(data, "SENSITIVE MATERIAL REPORT")
    lines += [
        "**Paths and categories only.** No matched string, no surrounding line, no "
        "excerpt and no sample of any file's contents appears in this document or in any "
        "other output of this tool. What is reported for each finding is: the path, the "
        "category, which detector fired, and how many times it fired. A count is metadata "
        "about content; it is not content.",
        "",
        "This is deliberate and structural. A sensitive-material report that quoted its "
        "evidence would be a second copy of every credential it found, in a document "
        "whose reassuring title guarantees it gets emailed and archived.",
        "",
        "Detectors are set to be eager. A false positive costs half a minute of looking at "
        "a file you wrote yourself; a false negative sends a credential into a "
        "reorganisation plan unflagged.",
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("Findings by category")
        lines += _absent_section("Findings by file")
        return _render(lines + _footer(data))

    findings = data["sensitive"]
    by_category: dict[str, list[dict[str, Any]]] = {}
    for finding in findings:
        by_category.setdefault(finding["category"], []).append(finding)

    lines += [
        "## Summary",
        "",
        *_table(
            ("category", "findings", "distinct files"),
            [(category, len(items), len({item["relpath"] for item in items}))
             for category, items in sorted(by_category.items())],
        ),
        "",
    ]
    for category in data["sensitive_categories"]:
        items = sorted(by_category.get(category, []), key=lambda item: (item["relpath"], item["detector"]))
        lines += [
            f"## {category}",
            "",
            *_table(
                ("path", "detector", "times detector fired"),
                [(item["relpath"], item["detector"], item["hits"]) for item in items],
            ),
            "",
        ]
    lines += [
        "## Handling",
        "",
        "- Nothing listed here has been copied, moved, quarantined or transmitted. The "
        "survey is read-only.",
        "- Nothing listed here should be committed to Git, pasted into a chat, or attached "
        "to an email until Mike has looked at the file himself.",
        "- Remediation is Mike's decision and is not proposed here.",
        "",
    ]
    return _render(lines + _footer(data))



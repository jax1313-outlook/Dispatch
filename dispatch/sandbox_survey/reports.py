"""The nine required documents, as pure functions over the survey dict.

Every generator here takes `SurveyResult.to_dict()` and returns a string. None
of them touches the filesystem, re-reads a Sandbox file, or consults anything
the JSON does not already contain. That is what makes the JSON and the prose
incapable of disagreeing, and it is what lets the whole reporting surface be
tested against hand-written dictionaries with no Sandbox anywhere in sight.

ONE RULE GOVERNS ALL NINE DOCUMENTS: **no report ever quotes file content.**

Not an excerpt, not a matched substring, not "the line that triggered the
detector", not a first paragraph, not a title read from inside a document. The
reports are built from paths, sizes, timestamps, hashes, class names, rule ids,
detector ids and counts -- metadata about content, never content. Adopting that
as an absolute rather than as a special case for the sensitive-material report
buys three things at once:

  * the sensitive report cannot leak a credential, because there is no
    machinery anywhere that could carry one into a document;
  * no report can accidentally reproduce an attestation of approval by the
    programme's principal, which this mission is forbidden to manufacture or
    to circulate as though it were authority;
  * the outputs are safe to email, paste and archive without anyone having to
    first check whether this particular Sandbox contained something private.

Every document carries the same header block: who generated it, when, which
Sandbox path was read, where the outputs went, the read-only declaration, and
the statement that nothing in it is accepted doctrine or a Mike decision. The
header is generated from one function, so no document can be shipped without it.
"""

from __future__ import annotations

import csv
import io
import json
from typing import Any, Callable, Iterable

_ABSENT = "ABSENT"


# --------------------------------------------------------------------------- header

def _rule_line() -> str:
    return "---"


def header_lines(data: dict[str, Any], title: str) -> list[str]:
    """The mandatory header, identical in shape across all nine documents."""
    performed = bool(data["survey_performed"])
    lines = [
        f"# {title}",
        "",
        f"- **Generated by:** {data['generated_by']}",
        f"- **Generated (UTC):** {data['generated_at']}",
        f"- **Tool:** `{data['tool']}` {data['tool_version']} — run `{data['run_id']}`",
        f"- **Sandbox path read:** `{data['sandbox_root']}`",
        f"- **Output path:** `{data['output_root']}`",
        f"- **Survey status:** `{data['status']}`",
        "",
        f"> **{data['read_only_declaration']}**",
        ">",
        f"> **{data['authority_declaration']}**",
        "",
    ]
    if not performed:
        lines += [
            "> **THIS SURVEY HAS NOT BEEN RUN.** This document is a template showing the "
            "shape of the output. No file under the Sandbox path above has been read, "
            "listed, hashed or classified.",
            ">",
            f"> Reason: {data['absent_reason']}",
            ">",
            f"> Every content claim in this document is `{_ABSENT}` — meaning the step was "
            "not performed, not that the material does not exist.",
            "",
        ]
    lines.append(_rule_line())
    lines.append("")
    return lines


def _absent_section(what: str) -> list[str]:
    return [
        f"## {what}",
        "",
        f"`{_ABSENT}` — the survey was not performed, so nothing is claimed here. "
        "Run the tool on the machine that holds the Sandbox (see "
        "`docs/readiness/SANDBOX_SURVEY_PROCEDURE.md`) and this section will be "
        "populated from what is actually on disk.",
        "",
    ]


def _cell(text: Any) -> str:
    """Markdown table cell. Pipes escaped; nothing else altered."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _table(headings: Iterable[str], rows: Iterable[Iterable[Any]]) -> list[str]:
    headings = list(headings)
    lines = [
        "| " + " | ".join(headings) + " |",
        "| " + " | ".join("---" for _ in headings) + " |",
    ]
    body = [
        "| " + " | ".join(_cell(value) for value in row) + " |"
        for row in rows
    ]
    if not body:
        return lines + ["| " + " | ".join("_none_" if index == 0 else "" for index in range(len(headings))) + " |"]
    return lines + body


def _yes_no(value: Any) -> str:
    return "Y" if value else "N"


def _classes(record: dict[str, Any]) -> str:
    return ", ".join(record["secondary_classes"]) or "-"


def _footer(data: dict[str, Any]) -> list[str]:
    return [
        "",
        _rule_line(),
        "",
        f"_{data['read_only_declaration']}_  ",
        f"_{data['authority_declaration']}_  ",
        "_No file content is quoted anywhere in this document — only paths, sizes, "
        "timestamps, hashes, class names, rule identifiers and counts._",
        "",
    ]


def _render(lines: list[str]) -> str:
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------- 1. inventory

INVENTORY_COLUMNS = (
    "path", "size_bytes", "modified_utc", "sha256", "primary_class",
    "secondary_classes", "dispatch_related", "text_confidence", "read_error",
    "duplicate_of", "classification_reasons",
)


def inventory_csv(data: dict[str, Any]) -> str:
    """Machine-readable inventory.

    The mandatory header is emitted as ``#``-prefixed comment lines above the
    column row. Readers must skip lines beginning with ``#`` -- which pandas,
    R and `csv` all do with one argument -- and in exchange the file carries its
    provenance and its read-only declaration with it, so a CSV that has been
    copied out of the output folder still says where it came from and what it
    is not.
    """
    buffer = io.StringIO()
    comments = [
        f"Generated by: {data['generated_by']}",
        f"Generated (UTC): {data['generated_at']}",
        f"Tool: {data['tool']} {data['tool_version']} run {data['run_id']}",
        f"Sandbox path read: {data['sandbox_root']}",
        f"Output path: {data['output_root']}",
        f"Survey status: {data['status']}",
        data["read_only_declaration"],
        data["authority_declaration"],
    ]
    if not data["survey_performed"]:
        comments.append(
            f"THIS SURVEY HAS NOT BEEN RUN — every content claim is {_ABSENT}. "
            f"Reason: {data['absent_reason']}"
        )
    for comment in comments:
        buffer.write(f"# {comment}\n")

    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(INVENTORY_COLUMNS)
    for record in data["files"]:
        writer.writerow([
            record["relpath"],
            record["size"],
            record["modified"],
            record["sha256"],
            record["primary_class"],
            ";".join(record["secondary_classes"]),
            _yes_no(record["dispatch_related"]),
            record["text_confidence"],
            record["read_error"],
            ";".join(record["duplicate_of"]),
            ";".join(record["reasons"]),
        ])
    return buffer.getvalue()


def inventory_markdown(data: dict[str, Any]) -> str:
    lines = header_lines(data, "SANDBOX FILE INVENTORY")
    counts = data["counts"]
    lines += [
        "The authoritative machine-readable form of this inventory is the CSV emitted "
        "alongside it. This document is the human summary of the same data.",
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("Every file found")
        lines += _absent_section("Counts by class")
        return _render(lines + _footer(data))

    lines += [
        "## Totals",
        "",
        *_table(
            ("measure", "value"),
            [
                ("files inventoried", counts["files"]),
                ("folders walked", counts["directories"]),
                ("total bytes", f"{counts['total_bytes']:,}"),
                ("unreadable or not-followed entries", counts["unreadable"]),
                ("Dispatch-related", counts["dispatch_related"]),
                ("files with sensitive findings", counts["sensitive_files"]),
                ("prior output-folder files (excluded from the map)", counts["prior_output_files"]),
            ],
        ),
        "",
        "## Counts by primary class",
        "",
        *_table(
            ("class", "files"),
            [(name, value) for name, value in counts["by_primary_class"].items() if value],
        ),
        "",
        "## Every file",
        "",
        *_table(
            ("path", "size", "modified (UTC)", "sha256 (first 16)", "primary",
             "secondary", "Dispatch?"),
            [
                (
                    record["relpath"], f"{record['size']:,}", record["modified"] or "-",
                    (record["sha256"] or "-")[:16], record["primary_class"],
                    _classes(record), _yes_no(record["dispatch_related"]),
                )
                for record in data["files"]
            ],
        ),
        "",
    ]

    prior = data["prior_output_files"]
    lines += [
        "## Prior output-folder contents (reported separately, never overwritten)",
        "",
        "These files were already in the output folder before this run. They are **not** "
        "part of the Sandbox inventory, are **not** classified, and are **not** compared "
        "for duplication against Sandbox material — otherwise each run's reports would "
        "feed the next run's map. Output filenames are timestamped, so nothing here was "
        "replaced.",
        "",
        *_table(
            ("path (relative to output folder)", "size", "modified (UTC)", "sha256 (first 16)"),
            [
                (item["relpath"], f"{item['size']:,}", item["modified"] or "-",
                 (item["sha256"] or "-")[:16])
                for item in prior
            ],
        ),
        "",
    ]
    if data["notes"]:
        lines += ["## Notes", ""] + [f"- {note}" for note in data["notes"]] + [""]
    return _render(lines + _footer(data))


# --------------------------------------------------------------------------- 2. knowledge map

def knowledge_map(data: dict[str, Any]) -> str:
    lines = header_lines(data, "SANDBOX KNOWLEDGE MAP")
    lines += [
        "## Rules of interpretation used to build this map",
        "",
        "These are reproduced verbatim from the mission that commissioned the survey. "
        "Every classification in every document here was made under them.",
        "",
    ]
    lines += [f"{index}. {rule}" for index, rule in enumerate(data["interpretation_rules"], 1)]
    lines += [
        "",
        "## What this map is not",
        "",
        "- It is not an inventory of what is true about the business. It is an inventory "
        "of what is on a disk.",
        "- It does not accept anything it found as doctrine. Material that reads as "
        "doctrine is listed as a **candidate** in GOVERNANCE_AND_DOCTRINE_CANDIDATES.",
        "- It does not record any decision as made. Material that reads as a decision is "
        "listed as a **candidate** in MIKE_DECISION_CANDIDATES.",
        "- It quotes no file's contents anywhere.",
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("What exists")
        lines += _absent_section("How it relates")
        lines += _absent_section("What appears current versus superseded")
        lines += _absent_section("Unresolved questions found")
        lines += _absent_section("Prompt assets and reusable Company Library candidates")
        return _render(lines + _footer(data))

    counts = data["counts"]
    files = data["files"]
    dispatch_files = [record for record in files if record["dispatch_related"]]
    other_files = [record for record in files if not record["dispatch_related"]]
    superseded = [record for record in files
                  if record["superseded_markers"] or "Historical" in _all_classes(record)]
    # Membership by path rather than by dict equality: two files with identical
    # metadata are still two files, and `record not in superseded` would drop
    # the second one.
    superseded_paths = {record["relpath"] for record in superseded}
    current = [record for record in files if record["relpath"] not in superseded_paths]
    questions = [record for record in files if record["unresolved_question_markers"]]
    prompts = [record for record in files if record["prompt_asset"]]
    library = [record for record in files if record["library_candidate"]]
    unknowns = [record for record in files if record["primary_class"] == "Unknown"]

    lines += [
        "## What exists",
        "",
        f"The survey walked {counts['directories']} folders and inventoried "
        f"{counts['files']} files totalling {counts['total_bytes']:,} bytes. "
        f"{counts['unreadable']} entries could not be read, or were links that were "
        "deliberately not followed; every one of them is still in the inventory, "
        "classified `Unknown` with its reason recorded, because a silently dropped file "
        "is the one outcome that would make the inventory lie.",
        "",
        *_table(
            ("primary class", "files", "what that class means here"),
            [(name, value, _CLASS_MEANINGS[name])
             for name, value in counts["by_primary_class"].items() if value],
        ),
        "",
        "### Folders holding the most material",
        "",
        *_table(
            ("folder", "files", "bytes"),
            _top_folders(files),
        ),
        "",
        "## How it relates",
        "",
        f"{len(dispatch_files)} files carry at least one Dispatch signal — a programme "
        "name, a freight-operations term, or a contracting term matched as a whole word. "
        f"{len(other_files)} do not, and are non-Dispatch material for the purposes of "
        "this programme. Being non-Dispatch is not a judgement about a file's value; it "
        "means the file is out of scope for this survey's conclusions.",
        "",
        *_table(
            ("Dispatch signal", "files"),
            _signal_counts(dispatch_files),
        ),
        "",
        "## What appears current versus superseded",
        "",
        f"{len(current)} files carry no supersession signal. {len(superseded)} do — "
        "either a filename or path placing them in an old/archive/legacy context, or "
        "supersession language in the read sample. **This is a signal, not a verdict.** "
        "A file marked superseded here may be the only correct copy, and a file with no "
        "signal may be years out of date; nothing in a filesystem records which of two "
        "documents a person still believes.",
        "",
        *_table(
            ("path", "primary", "supersession markers", "last modified (UTC)"),
            [(record["relpath"], record["primary_class"], record["superseded_markers"],
              record["modified"] or "-")
             for record in sorted(superseded, key=lambda item: item["relpath"])],
        ),
        "",
        "## Unresolved questions found",
        "",
        f"{len(questions)} files contain markers of an open question (TODO, TBD, FIXME, "
        "'open question', 'needs a decision', and similar). The count of markers is "
        "reported; the text of the questions is not, because this document quotes no "
        "file content. The files themselves are where the questions are.",
        "",
        *_table(
            ("path", "open-question markers", "primary"),
            [(record["relpath"], record["unresolved_question_markers"], record["primary_class"])
             for record in sorted(questions, key=lambda item: -item["unresolved_question_markers"])],
        ),
        "",
        "## Prompt assets and reusable Company Library candidates",
        "",
        f"{len(prompts)} files look like prompt assets (a prompt/instruction filename, or "
        "system-prompt structure in the sample). "
        f"{len(library)} look like reusable Company Library candidates (templates, "
        "checklists, standard procedures, playbooks) that are not personal material.",
        "",
        *_table(
            ("path", "prompt asset", "library candidate", "primary"),
            [(record["relpath"], _yes_no(record["prompt_asset"]),
              _yes_no(record["library_candidate"]), record["primary_class"])
             for record in sorted(prompts + [item for item in library if not item["prompt_asset"]],
                                  key=lambda item: item["relpath"])],
        ),
        "",
        "## What the survey could not determine",
        "",
        f"{len(unknowns)} files are `Unknown`. That is the honest answer for each of them: "
        "either no rule matched, or the file could not be read, or it is a link that was "
        "not followed. None of these were promoted to a more useful-looking class to "
        "reduce this number.",
        "",
        *_table(
            ("path", "why Unknown"),
            [(record["relpath"], "; ".join(record["reasons"])[:200])
             for record in sorted(unknowns, key=lambda item: item["relpath"])],
        ),
        "",
    ]
    return _render(lines + _footer(data))


_CLASS_MEANINGS: dict[str, str] = {
    "Knowledge": "reference material: notes, guides, source, documentation",
    "Evidence": "an artefact produced by an event: exports, logs, images, receipts",
    "Research": "exploration of options; architecture research is NOT accepted architecture",
    "Decision": "an explicit human decision with an identifiable actor",
    "Doctrine": "matches doctrine already locked in this mission or the repository",
    "Draft": "unfinished or explicitly marked draft/WIP",
    "Duplicate": "byte-identical or near-identical to another file (see POSSIBLE_DUPLICATES)",
    "Historical": "sits in an old/archive/legacy context or reads as superseded",
    "Personal": "personal material, out of programme scope",
    "Sensitive": "a sensitive-material detector fired (see SENSITIVE_MATERIAL_REPORT)",
    "Unknown": "no rule matched, unreadable, or a link that was not followed",
}


def _all_classes(record: dict[str, Any]) -> list[str]:
    return [record["primary_class"], *record["secondary_classes"]]


def _top_folders(files: list[dict[str, Any]], limit: int = 25) -> list[tuple[Any, ...]]:
    folders: dict[str, list[int]] = {}
    for record in files:
        folder = record["relpath"].rsplit("/", 1)[0] if "/" in record["relpath"] else "(root)"
        bucket = folders.setdefault(folder, [0, 0])
        bucket[0] += 1
        bucket[1] += int(record["size"])
    ranked = sorted(folders.items(), key=lambda item: (-item[1][0], item[0]))
    return [(name, count, f"{size:,}") for name, (count, size) in ranked[:limit]]


def _signal_counts(files: list[dict[str, Any]]) -> list[tuple[Any, ...]]:
    tally: dict[str, int] = {}
    for record in files:
        for signal in record["dispatch_signals"]:
            tally[signal] = tally.get(signal, 0) + 1
    return [(name, count) for name, count in sorted(tally.items(), key=lambda item: (-item[1], item[0]))]


# --------------------------------------------------------------------------- 3. research candidates

def research_candidates(data: dict[str, Any]) -> str:
    lines = header_lines(data, "DISPATCH RESEARCH CANDIDATES")
    lines += [
        "Architecture and research material that carries at least one Dispatch signal. "
        "**Architecture research is not accepted architecture.** Everything listed here "
        "is material that may be worth reading before the next architecture decision; "
        "none of it is an architecture decision, and none of it has been adopted.",
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("Research candidates")
        return _render(lines + _footer(data))

    candidates = [
        record for record in data["files"]
        if record["dispatch_related"]
        and ("Research" in _all_classes(record) or "Knowledge" in _all_classes(record))
    ]
    candidates.sort(key=lambda record: (record["primary_class"], record["relpath"]))
    lines += [
        f"{len(candidates)} of {data['counts']['files']} inventoried files qualify.",
        "",
        *_table(
            ("path", "primary", "secondary", "why it is relevant to Dispatch",
             "why it was classed this way", "modified (UTC)"),
            [
                (
                    record["relpath"], record["primary_class"], _classes(record),
                    "signals: " + (", ".join(record["dispatch_signals"]) or "-"),
                    "; ".join(record["reasons"])[:220],
                    record["modified"] or "-",
                )
                for record in candidates
            ],
        ),
        "",
        "## AI-generated material within this set",
        "",
        "Flagged separately because **AI-generated reports are not human decisions**, and "
        "an AI-written architecture note reads exactly like a human-written one.",
        "",
        *_table(
            ("path", "primary"),
            [(record["relpath"], record["primary_class"])
             for record in candidates if record["ai_generated"]],
        ),
        "",
    ]
    return _render(lines + _footer(data))


# --------------------------------------------------------------------------- 4. duplicates

def possible_duplicates(data: dict[str, Any]) -> str:
    lines = header_lines(data, "POSSIBLE DUPLICATES")
    lines += [
        "Two independent signals were run: exact SHA-256 grouping, and near-content "
        "detection by normalised-token shingling plus normalised-name/size proximity. "
        "**Every group below carries the evidence for the match**, so a claim you "
        "disagree with can be checked against its own working rather than taken on trust.",
        "",
        "Nothing here proposes a deletion. Duplicate detection produces a *secondary* "
        "class and a numbered, reversible proposal in PROPOSED_ORGANIZATION_ACTIONS. "
        "This tool contains no code path that can move, rename, merge or delete a file.",
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("Exact duplicates")
        lines += _absent_section("Near duplicates")
        return _render(lines + _footer(data))

    duplicate_data = data["duplicates"]
    lines += ["## Exact duplicates (byte-identical)", ""]
    lines += _group_section(duplicate_data["exact"])
    lines += ["", "## Near duplicates", ""]
    lines += _group_section(duplicate_data["near"])
    if duplicate_data["notes"]:
        lines += ["", "## Gaps in this analysis", ""]
        lines += [f"- {note}" for note in duplicate_data["notes"]]
    lines += [""]
    return _render(lines + _footer(data))


def _group_section(groups: list[dict[str, Any]]) -> list[str]:
    if not groups:
        return ["_None found._"]
    lines: list[str] = []
    for index, group in enumerate(groups, 1):
        lines += [
            f"### Group {index} — signal `{group['signal']}`, score {group['score']}",
            "",
            f"**Evidence:** {group['evidence']}",
            "",
        ]
        lines += [f"- `{member}`" for member in group["members"]]
        lines.append("")
    return lines



def proposed_organization_actions(data: dict[str, Any]) -> str:
    lines = header_lines(data, "PROPOSED ORGANIZATION ACTIONS")
    lines += [
        "> **NOTHING IN THIS DOCUMENT HAS BEEN EXECUTED, AND THIS TOOL CANNOT EXECUTE IT.**",
        ">",
        "> There is no code path in `dispatch.sandbox_survey` that performs a move, a "
        "rename, a merge or a deletion — not behind a flag, not behind a confirmation "
        "prompt, not at all. `tests/test_sandbox_survey.py` proves that by parsing the "
        "package's own source. Executing any action below is a separate decision by Mike, "
        "carried out by Mike, with tooling that does not yet exist.",
        "",
        "Every proposal is written to be reversible: a move records where the file came "
        "from, so undoing it is another move. No proposal deletes anything, merges file "
        "contents, or converts a file from one format to another.",
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("Proposed actions")
        lines += [
            "## Standing constraints on any future action list",
            "",
            *[f"{index}. {text}" for index, text in enumerate(_STANDING_CONSTRAINTS, 1)],
            "",
        ]
        return _render(lines + _footer(data))

    actions: list[tuple[str, str, str]] = []

    actions.append((
        f"Create the folder structure in PROPOSED_FOLDER_STRUCTURE under "
        f"`{data['sandbox_root']}`.",
        "No file moves. Creates empty folders only.",
        "Reversal: delete the empty folders.",
    ))

    tally: dict[str, list[str]] = {}
    for record in data["files"]:
        tally.setdefault(record["primary_class"], []).append(record["relpath"])
    for klass in sorted(tally):
        paths = sorted(tally[klass])
        actions.append((
            f"Move the {len(paths)} files classified `{klass}` to "
            f"`{_DESTINATIONS[klass]}`, preserving their relative subpaths.",
            f"Files: {len(paths)}. Full list is in the inventory CSV, column "
            f"`primary_class` = `{klass}`.",
            "Reversal: move each file back to the path recorded in the inventory CSV "
            "for this run.",
        ))

    exact_groups = data["duplicates"]["exact"]
    if exact_groups:
        actions.append((
            f"For each of the {len(exact_groups)} byte-identical groups in "
            "POSSIBLE_DUPLICATES, keep one copy in place and move the others to "
            "`70_Historical/duplicates/`.",
            "No deletion, no merge. The kept copy is Mike's choice, not the tool's; the "
            "tool states only that the files are byte-identical and gives the SHA-256.",
            "Reversal: move the copies back from `70_Historical/duplicates/`.",
        ))
    near_groups = data["duplicates"]["near"]
    if near_groups:
        actions.append((
            f"Review the {len(near_groups)} near-duplicate groups by hand before any "
            "of them is treated as a duplicate.",
            "Near-duplicate detection is a similarity signal with a stated score and "
            "stated evidence. It is not a finding of sameness, and no near-duplicate "
            "group should be collapsed on the strength of it alone.",
            "Reversal: none required; this is a reading task, not a change.",
        ))

    sensitive_paths = sorted({item["relpath"] for item in data["sensitive"]})
    if sensitive_paths:
        actions.append((
            f"Review the {len(sensitive_paths)} files listed in SENSITIVE_MATERIAL_REPORT "
            "and decide, per file, whether it should be moved to `90_Sensitive`, rotated "
            "and replaced, or left alone.",
            "The tool proposes no remediation. It does not know which credentials are "
            "live, which personal data is Mike's own, or which confidential material is "
            "held under an agreement that permits it.",
            "Reversal: any move is reversible via the inventory CSV.",
        ))

    candidates = sum(1 for record in data["files"] if record["doctrine_candidate"])
    if candidates:
        actions.append((
            f"Triage the {candidates} doctrine candidates in "
            "GOVERNANCE_AND_DOCTRINE_CANDIDATES: for each, Mike states whether it is "
            "doctrine, was doctrine, or was never doctrine.",
            "No file is promoted to doctrine by this tool under any circumstances. "
            "Notes are not doctrine.",
            "Reversal: none required; this produces a decision, not a change.",
        ))

    decisions = sum(1 for record in data["files"] if record["decision_candidate"])
    if decisions:
        actions.append((
            f"Triage the {decisions} decision candidates in MIKE_DECISION_CANDIDATES: "
            "for each, Mike states whether it was decided, by whom, and whether it holds.",
            "A file recording a decision is not proof the decision was made, and is "
            "certainly not proof it is still in force.",
            "Reversal: none required; this produces a decision, not a change.",
        ))

    lines += [
        "## Proposed actions",
        "",
        f"{len(actions)} proposals. Each awaits Mike's separate approval. None has run.",
        "",
    ]
    for index, (action, detail, reversal) in enumerate(actions, 1):
        lines += [
            f"### {index}. {action}",
            "",
            f"- **Detail:** {detail}",
            f"- **{reversal}**",
            "- **Status:** proposed — not executed, not approved, not scheduled.",
            "",
        ]
    lines += [
        "## Standing constraints on this action list",
        "",
        *[f"{index}. {text}" for index, text in enumerate(_STANDING_CONSTRAINTS, 1)],
        "",
    ]
    return _render(lines + _footer(data))


_STANDING_CONSTRAINTS: tuple[str, ...] = (
    "Nothing is executed by this tool. Executing any action is a separate Mike decision, "
    "performed with other tooling.",
    "Nothing is deleted. Ever. Superseded and duplicated material is moved, never removed.",
    "Nothing is merged and nothing is converted between formats.",
    "Every move is reversible from the inventory CSV of the run that proposed it.",
    "No file becomes doctrine, and no decision becomes a decision, by being moved into a "
    "folder with a confident name.",
    "The output folder is never reorganised by this list.",
)



def governance_and_doctrine_candidates(data: dict[str, Any]) -> str:
    lines = header_lines(data, "GOVERNANCE AND DOCTRINE CANDIDATES")
    lines += [
        "**Notes are not doctrine.** Nothing in this document is doctrine. Material is "
        "listed here as a *candidate* because it reads like doctrine — imperative "
        "sentences, policy language, a governance filename — which is a fact about its "
        "prose style, not about its authority.",
        "",
        "`Doctrine` as a class was assigned only where a file matches doctrine already "
        "locked in this mission or in the DISPATCH repository. Those anchors are listed "
        "below so a reader can see exactly what 'matches' meant.",
        "",
        "## Locked doctrine anchors used for matching",
        "",
        *_table(
            ("anchor", "what it locks"),
            [(anchor["anchor_id"], anchor["title"]) for anchor in data["locked_doctrine"]],
        ),
        "",
    ]
    if not data["survey_performed"]:
        lines += _absent_section("Material matching locked doctrine")
        lines += _absent_section("Doctrine candidates")
        lines += _absent_section("Material conflicting with locked doctrine")
        return _render(lines + _footer(data))

    matching = [record for record in data["files"] if record["matches_locked_doctrine"]]
    candidates = [record for record in data["files"] if record["doctrine_candidate"]]
    conflicting = [record for record in data["files"] if record["conflicts_with_locked_doctrine"]]

    lines += [
        "## Material that matches locked doctrine",
        "",
        f"{len(matching)} files. A match means the file repeats enough of a locked "
        "anchor's language to be talking about the same rule. It does **not** mean the "
        "file is an authoritative statement of that rule; the repository and this mission "
        "remain the source of the locked text.",
        "",
        *_table(
            ("path", "anchors matched", "primary"),
            [(record["relpath"], ", ".join(record["matches_locked_doctrine"]),
              record["primary_class"])
             for record in sorted(matching, key=lambda item: item["relpath"])],
        ),
        "",
        "## Doctrine candidates (reads as doctrine; matches nothing locked)",
        "",
        f"{len(candidates)} files. Each needs Mike to say whether it is doctrine, was "
        "doctrine, or was never doctrine. Until he does, it is none of the three.",
        "",
        *_table(
            ("path", "primary", "secondary", "why it reads as doctrine", "modified (UTC)"),
            [(record["relpath"], record["primary_class"], _classes(record),
              "; ".join(record["reasons"])[:200], record["modified"] or "-")
             for record in sorted(candidates, key=lambda item: item["relpath"])],
        ),
        "",
        "## Material that conflicts with locked doctrine",
        "",
        f"{len(conflicting)} files. Two conflicts are detectable without quoting anything: "
        "a document grading readiness in status words outside the locked truth vocabulary "
        "(`TRUTH_VOCABULARY`), and a document carrying an attestation that a named person "
        "approved, verified, accepted, authorised or confirmed something "
        "(`NO_MANUFACTURED_ATTESTATION`). The second is not an accusation: it means the "
        "file asserts an authority that this survey may neither manufacture nor accept as "
        "proof. Only Mike can confirm or deny it, and the attestation text is deliberately "
        "not reproduced here.",
        "",
        *_table(
            ("path", "conflicts with", "attestation claims found"),
            [(record["relpath"], ", ".join(record["conflicts_with_locked_doctrine"]),
              record["attestation_claims"])
             for record in sorted(conflicting, key=lambda item: item["relpath"])],
        ),
        "",
    ]
    return _render(lines + _footer(data))



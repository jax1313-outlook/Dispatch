def test_is_within_and_long_path():
    root = Path("/a/b")
    assert safety.is_within(root, root)
    assert safety.is_within(Path("/a/b/c"), root)
    assert not safety.is_within(Path("/a/x"), root)

    short = Path("/a/b")
    assert safety.long_path(short, windows=False) == "/a/b"
    assert safety.long_path(short, windows=True) == "/a/b"

    long_drive = Path("C:\\" + "x" * 300)
    assert safety.long_path(long_drive, windows=True).startswith("\\\\?\\C:")
    assert safety.long_path(long_drive, windows=False) == str(long_drive)

    unc = Path("\\\\server\\share\\" + "y" * 300)
    assert safety.long_path(unc, windows=True).startswith("\\\\?\\UNC")

    already = Path("\\\\?\\C:\\" + "z" * 300)
    assert safety.long_path(already, windows=True) == str(already)
    assert isinstance(safety.on_windows(), bool)



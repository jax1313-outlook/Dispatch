def test_writer_creates_the_file_under_the_root(tmp_path: Path):
    root = tmp_path / "out"
    root.mkdir()
    writer = safety.OutputWriter(output_root=root)
    target = writer.emit("SANDBOX_FILE_INVENTORY_20260824T131415Z.md", "content")
    assert target.parent == root
    assert target.read_text(encoding="utf-8") == "content"

    # A nested name resolves inside the root, but the writer does not create
    # directories -- only `prepare_output_root` may, and only the output root.
    # The refusal therefore comes from the OS, not from a silent mkdir.
    nested = writer.destination("nested/report.md")
    assert safety.is_within(nested, root)
    with pytest.raises(FileNotFoundError):
        writer.emit("nested/report.md", "content")
    assert not (root / "nested").exists()



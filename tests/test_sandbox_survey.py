"""Proof that the Sandbox survey is read-only, non-executing and non-leaking.

The survey tool exists to be pointed at somebody else's long-lived working
folder. Its entire value is a set of promises about what it does *not* do, so
these tests are written the way you would write them if you had to hand the
result to the folder's owner:

* `test_input_tree_is_byte_identical_after_a_full_run` records every input
  file's size, mtime and SHA-256 plus the complete directory listing before the
  run, and asserts afterwards that nothing changed and that the only new paths
  are inside the designated output folder.
* `test_no_move_rename_or_merge_code_path_exists` and its neighbours parse the
  package's own source. A promise enforced by documentation is a promise that
  survives exactly until the next refactor; a promise enforced by an AST walk
  fails the build.
* `test_a_fabricated_credential_never_reaches_any_output` puts a fake secret in
  the input tree and asserts the string appears in none of the eleven files
  written.

Nothing here runs against the real Sandbox. `D:\\Sandbox\\Play Pen` does not
exist in this environment and is never touched; every test builds its own tree
under `tmp_path`.
"""

